FLOOR_TOP = 0.034
"""
Where the warehouse's floor surface sits.

The robot's own frame has its wheels at zero, so its odom is lifted by this much for it
to stand on the floor rather than in it.
"""

STORAGE_TOP = 0.72
"""
Height of the flat top the parts are picked from.

Cast onto the drawn surface rather than taken from the stack's overall height: these
stacks are modelled as uneven piles, so their bounding box tops 20 cm above the only
part of them a thing can be set down on.
"""

STANDING_DISTANCE = 1
"""
How far the robot's base stands from a part it reaches for.

Set by the aisle rather than by the arm: a stack's collision geometry reaches out to
2.324 at the height of the base while its flat top only begins at 2.60, so the base
keeps its distance from the pile and the arm covers the rest.
"""

ROBOT_XY = (0.75, 6.0)
"""
Where the robot starts, in the open aisle between the two stacks it works at.
"""

BASE_MAY_DRIVE_WHILE_REACHING = False
"""
Whether the base may drive to help an arm reach (whole-body control).

Off, because every base pose in this plan is one that was captured deliberately: with it
on, a reach drives the base past the object and into the shelving.
"""

CARRYING_ARM = Arms.LEFT
"""
The arm that picks and places, one hand throughout.
"""

TICKS_PER_MOTION = 6000
"""
How long each motion may take before the run gives up on it.

Three times the default: a motion that has to hold itself off the shelving converges
more slowly than one that may drive straight at its goal, and the run is otherwise given
up on while it is still closing in.
"""

AVOIDS_COLLISIONS = True
"""
Whether every motion of the run carries a collision-avoidance goal.

On, because the hall is collided with: the racks the arm reaches into are geometry the
motions have to be held off, not just scenery the captured poses happen to miss.
"""

LYING_ON_ITS_SIDE = math.pi / 2
"""
Roll that tips a part off its own z-axis onto that axis' side.

It lays the axle down across the shelf front, and stands the plate on its rim.
"""

# %% the parts and where they belong


class PartMesh(StrEnum):
    """
    Mesh file of each part that is collected, which is also the body's name in the
    world.
    """

    SCREW_BOX = "screw_box.obj"
    WRENCH = "wrench.stl"
    AXLE = "axle.stl"
    PLATE = "plate.stl"


@dataclass(frozen=True)
class Part:
    """
    One part of the collection: what it is, where it lies, where it goes, and how the
    hand has to be turned to take hold of it.
    """

    mesh: PartMesh
    """
    The mesh the part is made of.
    """

    color: Color
    """
    What the part is painted, since an STL carries no color of its own.
    """

    storage_pose: Pose
    """
    Where the part lies on the storage rack at the start of the run.
    """

    storage_stand: Pose
    """
    Base pose the robot reaches :attr:`storage_pose` from.
    """

    delivery_pose: Pose
    """
    Where the part is put down on the delivery rack.

    Turned to face the robot, which stands on the opposite side of this stack from the
    one it picks at, so the part is put down from the front rather than reached around.
    """

    delivery_stand: Pose
    """
    Base pose the robot reaches :attr:`delivery_pose` from.
    """

    approach_direction: ApproachDirection
    """
    The side of the part the hand comes in from, in the part's own frame.
    """

    vertical_alignment: VerticalAlignment
    """
    Whether the hand comes down onto the part from above rather than in level with it.
    """

    rotate_gripper: bool
    """
    Whether the hand is rolled a quarter turn about its approach axis, which swaps the
    two faces the fingers can close on.
    """

    def grasp(self, end_effector: EndEffector) -> GraspDescription:
        """
        How this part is taken hold of.

        :param end_effector: The hand doing the grasping.
        """
        return GraspDescription(
            self.approach_direction,
            self.vertical_alignment,
            end_effector,
            rotate_gripper=self.rotate_gripper,
        )



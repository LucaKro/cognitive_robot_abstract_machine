# %% the demonstration


@dataclass(kw_only=True)
class PartsCollectionDemonstration(RobotDemonstration):
    """
    Collects four parts from two storage racks and delivers them to a third.
    """

    def build_simulated_world(self) -> World:
        world = self._hall_with_the_robot_in_it()
        self._let_the_base_rest_on_the_floor(world)
        return world

    @staticmethod
    def _let_the_base_rest_on_the_floor(world: World) -> None:
        """
        Stop the floor being an obstacle to the base that drives on it.

        A robot on wheels rests on the floor, so its base touches it wherever it stands
        and every pose it could be sent to counts as a collision otherwise. Only the
        base is freed; an arm still has to stay off the floor.

        :param world: The world holding the hall and the robot.
        """
        ground = [
            body
            for body in world.bodies
            if any(
                isinstance(shape, Mesh) and GROUND_MODEL in shape.filename
                for shape in body.collision
            )
        ]
        robot = world.get_semantic_annotations_by_type(Garmi)[0]
        with world.modify_world():
            world.collision_manager.add_ignore_collision_rule(
                AllowCollisionBetweenGroups(
                    body_group_a=ground,
                    body_group_b=list(robot.mobile_base.bodies_with_collision),
                )
            )

    def _hall_with_the_robot_in_it(self) -> World:
        """
        :return: The warehouse with the robot standing in its aisle.
        """
        return WorldSpecification.from_gazebo(
            ENV_URI,
            # The hall collides as a handful of boxes standing in for shapes drawn in
            # far more detail, which buries every ledge below a pile's top in solid
            # geometry. Colliding as it is drawn gives the decomposition the real shape.
            collision_from_visual=True,
            robots=[
                RobotSpecification(
                    semantic_annotation_type=self.used_robot,
                    world_T_odom=HomogeneousTransformationMatrix.from_xyz_rpy(
                        ROBOT_XY[0], ROBOT_XY[1], FLOOR_TOP
                    ),
                ),
            ],
        ).to_domain_object()

    def is_scene_populated(self, world: World) -> bool:
        present = {body.name.name for body in world.bodies}
        return all(part.mesh in present for part in PARTS)

    def populate_scene(self, world: World) -> None:
        for part in PARTS:
            # a pick-up takes the annotation of what it grasps, not the bare body, so
            # each part is spawned already named by one
            SemanticAnnotationWithRootSpecification(
                part.mesh,
                semantic_annotation_type=HasRootBody,
                # free to move (Connection6DoF), so the robot can pick it up and carry it
                root_specification=BodySpecification.mesh(
                    part.mesh,
                    os.path.join(_OBJECTS, part.mesh),
                    color=part.color,
                    parent_T_self=part.storage_pose.to_homogeneous_matrix(),
                    connection_specification=Connection6DoFSpecification(),
                ),
            ).spawn(world)

    def build_context(self, world: World) -> Context:
        with world.modify_world():
            WorldReasoner(world).reason()
        robot = world.get_semantic_annotations_by_type(self.used_robot)[0]
        # if isinstance(robot, HasMobileBase):
        #     robot.mobile_base.full_body_controlled = BASE_MAY_DRIVE_WHILE_REACHING
        context = Context(
            world=world,
            robot=robot,
            _debug=True,
            ros_node=self.ros_node,
            ticks_per_motion=TICKS_PER_MOTION,
        )
        context.evaluate_conditions = False
        return context

    def build_plan(self, context: Context) -> PlanNode:
        world = context.world  # bodies/poses below are resolved against it
        end_effector = ViewManager.get_end_effector_view(CARRYING_ARM, context.robot)
        steps = [
            self.carry(
                context,
                self.annotation_of(world, part.mesh),
                part.grasp(end_effector),
                part.delivery_pose,
            )
            for part in PARTS
        ]
        return sequential(steps, context=context).plan

    @staticmethod
    def annotation_of(world: World, mesh: PartMesh) -> HasRootBody:
        """
        The annotation naming one of the collected parts.

        :param world: The world the part was spawned in.
        :param mesh: The mesh the part is made of, which is also its body's name.
        """
        body = world.get_body_by_name(mesh)
        return next(
            annotation
            for annotation in world.get_semantic_annotations_by_type(HasRootBody)
            if annotation.root is body
        )

    def carry(
        self,
        context: Context,
        part: HasRootBody,
        grasp: GraspDescription,
        destination: Pose,
    ) -> TransportAction:
        """
        One leg: fetch a part from where it lies and put it down at ``destination``.

        The base pose for either end is left to the transport, which searches the floor
        around the part and around where it is going for somewhere the arm reaches from.

        :param context: The plan context the action is built against.
        :param part: The annotation of the part being carried.
        :param grasp: How the part is taken hold of.
        :param destination: Where the part is put down.
        """
        return TransportAction(
            object_designator=part,
            target_location=self.against_world_root(context, destination),
            arm=CARRYING_ARM,
            grasp_description=grasp,
        )

    @staticmethod
    def against_world_root(context: Context, pose: Pose) -> Pose:
        """
        A pose from this file, expressed in the world it is used in.

        :param context: The plan context holding that world.
        :param pose: The pose to re-reference.
        """
        return Pose(
            pose.to_position(),
            pose.to_quaternion(),
            reference_frame=context.world.root,
        )


def main() -> None:
    """
    Run the demonstration.

    RobotDemonstration.run() acquires the world, starts the visualization backend,
    attaches the plan and performs it. The backend defaults to CRAMERA (the browser
    viewer); CORAPLEX_VISUALIZATION overrides it, so `cramera-live` works unchanged and
    you can also force RVIZ / NONE from the outside.
    """
    PartsCollectionDemonstration(
        used_robot=Garmi,
        collision_avoidance=AVOIDS_COLLISIONS,
        # default_visualization_backend=VisualizationBackend.CRAMERA,
    ).run()


if __name__ == "__main__":
    main()
